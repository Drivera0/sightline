"""Hard-negative mining (docs/LANE_A_ML.md §6.5).

A false positive is a prediction with ``conf ≥ 0.25`` and IoU < 0.1 to every true box. For each
one we cut the 1024 tile centred on it (clamped to the image) with that tile's true labels
(often none) and write it as an extra training tile.

Tiles go to a **separate** folder (default ``data/heridal/hard_negatives``) so run 1's dataset
stays reproducible; ``write_dataset_yaml`` makes a YAML whose ``train`` lists both folders.
"""

from __future__ import annotations

import random
from collections.abc import Sequence
from pathlib import Path
from typing import Protocol

from sightline.ml.evaluate import iou
from sightline.ml.tiling import TILE_PX, Tile, boxes_in_tile
from sightline.ml.types import Box, LabeledImage, RawDetection
from sightline.ml.voc import yolo_line

FP_IOU = 0.1
DEFAULT_OUT = Path("data/heridal/hard_negatives")


class TiledDetector(Protocol):
    def detect_tiled(
        self, image: Path, conf: float = 0.05, slice_px: int = 1024, overlap: float = 0.2
    ) -> list[RawDetection]: ...


def false_positives(
    dets: Sequence[RawDetection], truth: Sequence[Box], conf: float = 0.25
) -> list[Box]:
    return [d.box for d in dets if d.conf >= conf and all(iou(d.box, t) < FP_IOU for t in truth)]


def tile_around(box: Box, width: int, height: int, tile_px: int = TILE_PX) -> Tile:
    """``tile_px`` square centred on the box, shifted to stay inside the image."""
    cx, cy = box.center
    x0 = round(cx - tile_px / 2)
    y0 = round(cy - tile_px / 2)
    x0 = max(0, min(x0, width - tile_px)) if width > tile_px else 0
    y0 = max(0, min(y0, height - tile_px)) if height > tile_px else 0
    return Tile(x0, y0, min(x0 + tile_px, width), min(y0 + tile_px, height))


def mine(
    detector: TiledDetector,
    train: Sequence[LabeledImage],
    conf: float = 0.25,
    max_tiles: int = 2000,
    seed: int = 7,
    out_dir: Path = DEFAULT_OUT,
    quality: int = 95,
) -> list[Path]:
    """Tiled inference over **training** images, cut a tile around every false positive,
    cap at ``max_tiles`` (seeded sample), write ``<out_dir>/{images,labels}``. Returns the tile paths."""
    from PIL import Image

    candidates: list[tuple[LabeledImage, Tile]] = []
    seen: set[tuple[str, int, int]] = set()
    for im in train:
        dets = detector.detect_tiled(im.path, conf=conf)
        for fp in false_positives(dets, im.boxes, conf):
            tile = tile_around(fp, im.width, im.height)
            key = (im.path.stem, tile.x0, tile.y0)
            if key not in seen:
                seen.add(key)
                candidates.append((im, tile))

    rng = random.Random(seed)
    if len(candidates) > max_tiles:
        candidates = rng.sample(candidates, max_tiles)
    candidates.sort(key=lambda c: (c[0].path.stem, c[1].x0, c[1].y0))

    images_dir, labels_dir = out_dir / "images", out_dir / "labels"
    images_dir.mkdir(parents=True, exist_ok=True)
    labels_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for im, tile in candidates:
        name = f"{im.path.stem}_hn_{tile.x0}_{tile.y0}"
        with Image.open(im.path) as src:
            src.convert("RGB").crop((tile.x0, tile.y0, tile.x1, tile.y1)).save(
                images_dir / f"{name}.jpg", "JPEG", quality=quality
            )
        lines = [
            yolo_line(b, tile.width_px, tile.height_px) for b in boxes_in_tile(list(im.boxes), tile)
        ]
        (labels_dir / f"{name}.txt").write_text(
            "\n".join(lines) + ("\n" if lines else ""), encoding="utf-8"
        )
        written.append(images_dir / f"{name}.jpg")
    return written


def write_dataset_yaml(tiles_root: Path, hn_root: Path, out: Path) -> None:
    """A YAML whose ``train`` is the original tiles plus the hard-negative tiles; ``val`` unchanged."""
    text = (
        "# HERIDAL tiles + hard negatives (generated by sightline.ml.hard_negatives)\n"
        "path: .\n"
        "train:\n"
        f"  - {tiles_root.resolve().as_posix()}/train/images\n"
        f"  - {hn_root.resolve().as_posix()}/images\n"
        f"val: {tiles_root.resolve().as_posix()}/val/images\n"
        "names:\n"
        "  0: person\n"
    )
    out.write_text(text, encoding="utf-8")
