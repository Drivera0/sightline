"""Cut yolo_full train/val images into 1024 px tiles for training. Data prep, lane A.

    python scripts/tile_dataset.py [--src data/heridal/yolo_full] [--out data/heridal/yolo_tiles]
                                   [--tile 1024] [--overlap 0.2] [--empty-frac 0.25] [--seed 7]
                                   [--workers N] [--quality 95]

Output (docs/LANE_A_ML.md §6.1):

    data/heridal/yolo_tiles/{train,val}/images/<id>_<x0>_<y0>.jpg
    data/heridal/yolo_tiles/{train,val}/labels/<id>_<x0>_<y0>.txt   # empty file = background tile
    data/heridal/yolo_tiles/dataset.yaml
    data/heridal/yolo_tiles/tile_report.json

The test split is never tiled here: evaluation runs on full test images with sliced inference.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from concurrent.futures import ProcessPoolExecutor, as_completed
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:  # until the package is installed with uv
    sys.path.insert(0, str(ROOT))


SPLITS = ("train", "val")


def tile_one(
    image_path: Path,
    label_path: Path,
    out_images: Path,
    out_labels: Path,
    tile_px: int,
    overlap: float,
    empty_frac: float,
    seed: int,
    quality: int,
) -> dict[str, int]:
    """Tile one image; returns counts. Runs in a worker process."""
    from PIL import Image

    from sightline.ml.tiling import tiles_for_image
    from sightline.ml.voc import read_yolo_labels, yolo_line

    with Image.open(image_path) as im:
        im = im.convert("RGB")
        width, height = im.size
        boxes = read_yolo_labels(label_path, width, height)
        chosen = tiles_for_image(
            width, height, boxes, image_path.stem, tile_px, overlap, empty_frac, seed
        )
        n_boxes = 0
        for tile, tile_boxes in chosen:
            name = tile.name(image_path.stem)
            crop = im.crop((tile.x0, tile.y0, tile.x1, tile.y1))
            crop.save(out_images / f"{name}.jpg", "JPEG", quality=quality)
            lines = [yolo_line(b, tile.width_px, tile.height_px) for b in tile_boxes]
            (out_labels / f"{name}.txt").write_text(
                "\n".join(lines) + ("\n" if lines else ""), encoding="utf-8"
            )
            n_boxes += len(tile_boxes)
    n_pos = sum(1 for _, b in chosen if b)
    return {
        "images": 1,
        "source_boxes": len(boxes),
        "tiles": len(chosen),
        "positive_tiles": n_pos,
        "empty_tiles": len(chosen) - n_pos,
        "tile_boxes": n_boxes,
    }


def tile_split(name: str, src: Path, out: Path, args: argparse.Namespace) -> dict[str, int]:
    images = sorted((src / name / "images").glob("*.jpg"))
    out_images, out_labels = out / name / "images", out / name / "labels"
    out_images.mkdir(parents=True, exist_ok=True)
    out_labels.mkdir(parents=True, exist_ok=True)
    totals: dict[str, int] = {}
    print(f"{name}: {len(images)} images", flush=True)
    with ProcessPoolExecutor(max_workers=args.workers) as pool:
        futures = [
            pool.submit(
                tile_one,
                img,
                src / name / "labels" / f"{img.stem}.txt",
                out_images,
                out_labels,
                args.tile,
                args.overlap,
                args.empty_frac,
                args.seed,
                args.quality,
            )
            for img in images
        ]
        for i, fut in enumerate(as_completed(futures), 1):
            for k, v in fut.result().items():
                totals[k] = totals.get(k, 0) + v
            if i % 100 == 0 or i == len(futures):
                print(
                    f"  {name}: {i}/{len(futures)} images, {totals.get('tiles', 0)} tiles",
                    flush=True,
                )
    return totals


def write_dataset_yaml(out: Path) -> None:
    text = (
        f"# HERIDAL 1024 px tiles (generated by scripts/tile_dataset.py)\n"
        f"path: {out.resolve().as_posix()}\n"
        f"train: train/images\n"
        f"val: val/images\n"
        f"names:\n"
        f"  0: person\n"
    )
    (out / "dataset.yaml").write_text(text, encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--src", type=Path, default=ROOT / "data/heridal/yolo_full")
    ap.add_argument("--out", type=Path, default=ROOT / "data/heridal/yolo_tiles")
    ap.add_argument("--tile", type=int, default=1024)
    ap.add_argument("--overlap", type=float, default=0.2)
    ap.add_argument("--empty-frac", type=float, default=0.25)
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--workers", type=int, default=None, help="default: CPU count")
    ap.add_argument("--quality", type=int, default=95, help="JPEG quality for tiles")
    args = ap.parse_args(argv)

    for name in SPLITS:
        if not (args.src / name / "images").exists():
            print(
                f"error: {args.src / name / 'images'} not found; run scripts/convert_heridal.py first",
                file=sys.stderr,
            )
            return 2

    t0 = time.time()
    report: dict[str, object] = {
        "source": str(args.src),
        "tile_px": args.tile,
        "overlap": args.overlap,
        "empty_keep_frac": args.empty_frac,
        "seed": args.seed,
        "jpeg_quality": args.quality,
        "splits": {name: tile_split(name, args.src, args.out, args) for name in SPLITS},
    }
    report["seconds"] = round(time.time() - t0, 1)
    write_dataset_yaml(args.out)
    (args.out / "tile_report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps(report, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
